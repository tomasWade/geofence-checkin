CREATE TABLE checkin_rule (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  fence_id BIGINT NOT NULL,
  work_start_sec INT NOT NULL,
  work_end_sec INT NOT NULL,
  late_tolerance_sec INT NOT NULL DEFAULT 0,
  effective_days SMALLINT NOT NULL DEFAULT 127,
  bind_type VARCHAR(20) NOT NULL DEFAULT 'ALL',
  status SMALLINT NOT NULL DEFAULT 1,
  deleted SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON COLUMN checkin_rule.work_start_sec IS '上班时刻，当日偏移秒数';
COMMENT ON COLUMN checkin_rule.work_end_sec IS '下班时刻，当日偏移秒数';
COMMENT ON COLUMN checkin_rule.late_tolerance_sec IS '迟到宽限秒数';
COMMENT ON COLUMN checkin_rule.effective_days IS 'bit0~bit6 周一~周日';
COMMENT ON COLUMN checkin_rule.bind_type IS 'ALL/ROLE/GROUP/USER';

CREATE TABLE checkin_rule_scope (
  rule_id BIGINT NOT NULL,
  role_id BIGINT,
  group_id BIGINT,
  user_id BIGINT
);
CREATE INDEX idx_scope_rule ON checkin_rule_scope (rule_id);

CREATE TABLE daily_report (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  checkin_date DATE NOT NULL,
  first_in_time TIMESTAMP,
  last_out_time TIMESTAMP,
  work_minutes INT,
  status_enum INT NOT NULL DEFAULT 0,
  CONSTRAINT uk_report_user_date UNIQUE (user_id, checkin_date)
);
COMMENT ON COLUMN daily_report.status_enum IS 'bitmap 1迟到 2早退 4缺卡 8旷工 16地点异常';
CREATE INDEX idx_report_date ON daily_report (checkin_date);
