CREATE TABLE sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  real_name VARCHAR(50),
  mobile VARCHAR(20),
  status SMALLINT NOT NULL DEFAULT 1,
  deleted SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON COLUMN sys_user.status IS '1启用 0禁用';

CREATE TABLE sys_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_code VARCHAR(50) NOT NULL UNIQUE,
  role_name VARCHAR(50) NOT NULL,
  data_scope VARCHAR(20) NOT NULL DEFAULT 'SELF',
  remark VARCHAR(200)
);
COMMENT ON COLUMN sys_role.data_scope IS 'SELF/GROUP/ALL';

CREATE TABLE sys_permission (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  perm_code VARCHAR(100) NOT NULL UNIQUE,
  perm_name VARCHAR(100) NOT NULL,
  type VARCHAR(20) NOT NULL DEFAULT 'api',
  parent_id BIGINT NOT NULL DEFAULT 0
);
COMMENT ON COLUMN sys_permission.type IS 'menu/button/api';

CREATE TABLE sys_user_role (
  user_id BIGINT NOT NULL,
  role_id BIGINT NOT NULL,
  PRIMARY KEY (user_id, role_id)
);

CREATE TABLE sys_role_permission (
  role_id BIGINT NOT NULL,
  permission_id BIGINT NOT NULL,
  PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE sys_group (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  manager_user_id BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sys_group_member (
  group_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  PRIMARY KEY (group_id, user_id)
);

CREATE TABLE geo_fence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  lng NUMERIC(10,6) NOT NULL,
  lat NUMERIC(10,6) NOT NULL,
  radius_m INT NOT NULL DEFAULT 150,
  fence_type VARCHAR(20) NOT NULL DEFAULT 'circle',
  status SMALLINT NOT NULL DEFAULT 1,
  deleted SMALLINT NOT NULL DEFAULT 0,
  created_by BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON COLUMN geo_fence.status IS '1启用 0停用';
CREATE INDEX idx_geo_fence_status ON geo_fence (status);

CREATE TABLE checkin_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  fence_id BIGINT NOT NULL,
  checkin_date DATE NOT NULL,
  checkin_time TIMESTAMP NOT NULL,
  client_time TIMESTAMP,
  lng NUMERIC(10,6) NOT NULL,
  lat NUMERIC(10,6) NOT NULL,
  accuracy_m DOUBLE PRECISION,
  distance_m DOUBLE PRECISION NOT NULL,
  source VARCHAR(20) NOT NULL DEFAULT 'H5',
  manual_by BIGINT,
  suspicious SMALLINT NOT NULL DEFAULT 0,
  remark VARCHAR(500)
);
COMMENT ON COLUMN checkin_record.checkin_time IS '服务端时间，判定与落账唯一时间源';
COMMENT ON COLUMN checkin_record.client_time IS '端上时间，仅存档对照';
CREATE INDEX idx_record_user_date ON checkin_record (user_id, checkin_date);
CREATE INDEX idx_record_date ON checkin_record (checkin_date);

CREATE TABLE sys_audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  action VARCHAR(50) NOT NULL,
  resource VARCHAR(200),
  detail_json TEXT,
  ip VARCHAR(50),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_created ON sys_audit_log (created_at);
